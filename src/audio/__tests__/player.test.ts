import { beforeEach, describe, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ sounds: [] as any[], resume: vi.fn(() => Promise.resolve()) }))
vi.mock('howler', () => ({
  Howler: { ctx: { resume: mocks.resume } },
  Howl: class {
    options: any; active = false; next = 0
    state = vi.fn(() => 'loaded')
    load = vi.fn()
    play = vi.fn(() => { this.active = true; return ++this.next })
    playing = vi.fn(() => this.active)
    pause = vi.fn(() => { this.active = false })
    stop = vi.fn()
    mute = vi.fn()
    volume = vi.fn()
    rate = vi.fn()
    unload = vi.fn()
    constructor(options: any) { this.options = options; mocks.sounds.push(this) }
  },
}))
import { createAudioPlayer } from '../player'
import { soundForEvent } from '../catalog'
import { Game, PLAYER_IDS } from '../../core'
import type { GameEvent } from '../../core'

beforeEach(() => { mocks.sounds.length = 0; mocks.resume.mockClear() })
function combatEvents() {
  const game = new Game({ random: () => .35 })
  while (game.state.phase.name === 'roll') {
    const phase = game.state.phase
    game.dispatch({ type: phase.step === 'awaiting-roll' ? 'RollDice' : 'ConfirmRoll', playerId: phase.activePlayerId })
  }
  PLAYER_IDS.forEach(playerId => game.dispatch({ type: 'SkipFavor', playerId }))
  const result = game.dispatch({ type: 'ResolveRound', playerId: 'player-1' })
  if (!result.ok) throw new Error(result.error.message)
  return result.events
}
describe('owned audio lifecycle', () => {
  it('keeps playing effects and music through repeated visible notifications', () => {
    const player = createAudioPlayer()
    player.unlock()
    player.impact(0, 1)
    const effect = mocks.sounds[0]
    const track = mocks.sounds.find(s => s.options.src[0].endsWith('background-1.opus'))
    player.visibility(false)
    player.visibility(false)
    expect(effect.stop).not.toHaveBeenCalled()
    expect(track.pause).not.toHaveBeenCalled()
    player.visibility(true)
    expect(effect.stop).toHaveBeenCalledTimes(1)
    expect(track.pause).toHaveBeenCalledTimes(1)
    player.dispose()
  })
  it('creates audio only after interaction, starts each loaded loop once, and caps contact polyphony', () => {
    const player = createAudioPlayer()
    player.impact(0, 1)
    expect(mocks.sounds).toHaveLength(0)
    player.unlock(); player.unlock()
    expect(mocks.sounds).toHaveLength(15)
    mocks.sounds.forEach(sound => sound.options.onload())
    const loops = mocks.sounds.filter(s => s.options.loop)
    expect(loops.every(s => s.play.mock.calls.length === 1)).toBe(true)
    for (let i = 0; i < 20; i++) player.impact(i, .4)
    expect(mocks.sounds.reduce((n,s) => n + s.stop.mock.calls.length, 0)).toBe(12)
    player.dispose()
    expect(mocks.sounds.every(s => s.unload.mock.calls.length === 1)).toBe(true)
    player.unlock()
    expect(mocks.sounds).toHaveLength(15)
  })
  it('applies separate levels, silence and visibility without queuing late contacts', () => {
    const player = createAudioPlayer()
    player.unlock()
    const hit = mocks.sounds[0]
    hit.state.mockReturnValue('loading')
    player.impact(0, 1)
    expect(hit.play).not.toHaveBeenCalled()
    hit.state.mockReturnValue('loaded')
    player.configure({ music: .2, effects: .8, muted: false })
    expect(mocks.sounds.at(-1).volume).toHaveBeenLastCalledWith(.2 * .7)
    player.visibility(true); player.impact(0, 1)
    expect(hit.play).not.toHaveBeenCalled()
    expect(mocks.sounds.find(s => s.options.src[0].endsWith('background-1.opus')).pause).toHaveBeenCalled()
    player.visibility(false); player.impact(0, 1)
    expect(hit.play).toHaveBeenCalledTimes(1)
    player.configure({ music: .2, effects: .8, muted: true }); player.impact(0, 1)
    expect(hit.play).toHaveBeenCalledTimes(1)
    player.dispose()
  })
  it('keeps a load failure visible until that same sound recovers', () => {
    const failed = vi.fn(), player = createAudioPlayer(failed)
    player.unlock()
    mocks.sounds[0].options.onloaderror()
    mocks.sounds[1].options.onload()
    expect(failed).toHaveBeenLastCalledWith(true)
    mocks.sounds[0].options.onload()
    expect(failed).toHaveBeenLastCalledWith(false)
    player.dispose()
  })
  it('maps real combat events without mutating their authoritative result', () => {
    const events = combatEvents(), snapshot = JSON.stringify(events), player = createAudioPlayer()
    player.unlock()
    events.forEach(event => player.event(event))
    expect(events.some(event => soundForEvent(event) === 'attack')).toBe(true)
    expect(JSON.stringify(events)).toBe(snapshot)
    player.dispose()
  })
})

function music() {
  return [1, 2].map(index => mocks.sounds.find(sound => sound.options.src[0].endsWith(`background-${index}.opus`)))
}
function finish(sound: any) {
  sound.active = false
  sound.options.onend(sound.next)
}
describe('sequential background playlist', () => {
  it('streams the two tracks in order and wraps without looping or overlapping music', () => {
    const player = createAudioPlayer()
    player.unlock()
    const [first, second] = music()
    expect(first.options.html5).toBe(true)
    expect(second.options.html5).toBe(true)
    expect(first.options.loop).toBe(false)
    expect(second.options.loop).toBe(false)
    expect(first.play).toHaveBeenCalledTimes(1)
    expect(second.play).not.toHaveBeenCalled()
    finish(first)
    expect(first.active).toBe(false)
    expect(second.play).toHaveBeenCalledTimes(1)
    // A stale end from the previous track cannot advance the new one.
    first.options.onend(first.next)
    expect(first.play).toHaveBeenCalledTimes(1)
    finish(second)
    expect(second.active).toBe(false)
    expect(first.play).toHaveBeenCalledTimes(2)
    player.dispose()
  })
  it('preserves playlist position while hidden, muted or at zero music volume', () => {
    const player = createAudioPlayer()
    player.unlock()
    const [first, second] = music()
    finish(first)
    player.visibility(true)
    expect(second.active).toBe(false)
    player.visibility(false)
    expect(second.play).toHaveBeenCalledTimes(2)
    player.configure({ music: 0, effects: .6, muted: false })
    expect(second.active).toBe(false)
    player.configure({ music: .4, effects: .6, muted: true })
    expect(second.active).toBe(false)
    player.configure({ music: .4, effects: .6, muted: false })
    expect(second.play).toHaveBeenCalledTimes(3)
    expect(first.play).toHaveBeenCalledTimes(1)
    player.dispose()
  })
  it('waits for the next track to load and never restarts the finished track', () => {
    const player = createAudioPlayer()
    player.unlock()
    const [first, second] = music()
    second.state.mockReturnValue('loading')
    finish(first)
    expect(first.play).toHaveBeenCalledTimes(1)
    expect(second.play).not.toHaveBeenCalled()
    second.state.mockReturnValue('loaded')
    second.options.onload()
    player.unlock()
    expect(second.play).toHaveBeenCalledTimes(1)
    player.dispose()
    second.options.onend(second.next)
    expect(first.play).toHaveBeenCalledTimes(1)
  })
  it('defers an end arriving during a pause until visibility returns', () => {
    const player = createAudioPlayer()
    player.unlock()
    const [first, second] = music()
    player.visibility(true)
    finish(first)
    expect(second.play).not.toHaveBeenCalled()
    player.visibility(false)
    expect(second.play).toHaveBeenCalledTimes(1)
    player.dispose()
  })
})

describe('coin toss sound', () => {
  it('plays the supplied recording once at its original speed using the effect level', () => {
    const player = createAudioPlayer()
    player.coinFlip()
    expect(mocks.sounds).toHaveLength(0)
    player.unlock()
    player.configure({ music: .1, effects: .45, muted: false })
    const coin = mocks.sounds.find(s => s.options.src[0].endsWith('coin-flip.wav'))
    expect(coin.play).not.toHaveBeenCalled()
    expect(coin.options.loop).toBe(false)
    player.coinFlip()
    expect(coin.play).toHaveBeenCalledTimes(1)
    expect(coin.volume).toHaveBeenLastCalledWith(.45, 1)
    expect(coin.rate).toHaveBeenLastCalledWith(1, 1)
    player.stopEffects()
    expect(coin.stop).toHaveBeenCalledWith(1)
    player.dispose()
  })
  it('does not play muted, paused, unloaded or disposed tosses or replay a late load', () => {
    const player = createAudioPlayer()
    player.unlock()
    const coin = mocks.sounds.find(s => s.options.src[0].endsWith('coin-flip.wav'))
    coin.state.mockReturnValue('loading')
    player.coinFlip()
    coin.state.mockReturnValue('loaded')
    coin.options.onload()
    expect(coin.play).not.toHaveBeenCalled()
    player.visibility(true)
    player.coinFlip()
    player.visibility(false)
    player.configure({ music: .1, effects: 0, muted: false })
    player.coinFlip()
    player.configure({ music: .1, effects: .5, muted: true })
    player.coinFlip()
    player.dispose()
    player.coinFlip()
    expect(coin.play).not.toHaveBeenCalled()
  })
})

describe('match start sound', () => {
  it('plays the supplied effect once per call without looping or changing speed', () => {
    const player = createAudioPlayer()
    player.unlock()
    player.configure({ music: .2, effects: .55, muted: false })
    const start = mocks.sounds.find(s => s.options.src[0].endsWith('game-start.wav'))
    expect(start.play).not.toHaveBeenCalled()
    expect(start.options.loop).toBe(false)
    player.gameStart()
    expect(start.play).toHaveBeenCalledTimes(1)
    expect(start.volume).toHaveBeenLastCalledWith(.55, 1)
    expect(start.rate).toHaveBeenLastCalledWith(1, 1)
    finish(start)
    expect(start.play).toHaveBeenCalledTimes(1)
    player.visibility(true)
    player.gameStart()
    player.visibility(false)
    expect(start.play).toHaveBeenCalledTimes(1)
    player.configure({ music: .2, effects: 0, muted: false })
    player.gameStart()
    expect(start.play).toHaveBeenCalledTimes(1)
    player.dispose()
    player.gameStart()
    expect(start.play).toHaveBeenCalledTimes(1)
  })
})

describe('earning money sound', () => {
  const base = { id: 'earn-test', sequence: 6, round: 1, revision: 3, playerId: 'player-1' } as const
  const gained: Extract<GameEvent, { type: 'TokensGained' }> = { ...base, type: 'TokensGained', dieIds: ['player-1/die-1', 'player-1/die-2'], tokens: 2 }
  const granted: Extract<GameEvent, { type: 'TokensGranted' }> = { ...base, type: 'TokensGranted', favorId: 'bragis-verve', amount: 3, tokens: 5 }
  const stolen: Extract<GameEvent, { type: 'TokensStolen' }> = { ...base, type: 'TokensStolen', targetId: 'player-2', dieIds: ['player-1/die-3'], amount: 2, tokens: 7, targetTokens: 0 }
  it('uses the new recording only for positive earnings, preserving spending sounds', () => {
    for (const event of [gained, granted, stolen]) expect(soundForEvent(event)).toBe('earn-money')
    expect(soundForEvent({ ...gained, dieIds: [] })).toBeUndefined()
    expect(soundForEvent({ ...granted, amount: 0 })).toBeUndefined()
    expect(soundForEvent({ ...stolen, amount: 0 })).toBeUndefined()
    expect(soundForEvent({ ...base, type: 'TokensDestroyed', targetId: 'player-2', favorId: 'skulds-claim', amount: 1, tokens: 0 })).toBe('token')
  })
  it('plays once on the first arrival of each earnings event, at the original speed', () => {
    const player = createAudioPlayer()
    player.unlock()
    player.configure({ music: .2, effects: .4, muted: false })
    const earn = mocks.sounds.find(s => s.options.src[0].endsWith('earn-money.wav'))
    expect(earn.options.loop).toBe(false)
    expect(earn.play).not.toHaveBeenCalled()
    player.event(granted, 1)
    player.event(granted, 2)
    player.event(granted, 3)
    expect(earn.play).toHaveBeenCalledTimes(1)
    expect(earn.rate).toHaveBeenLastCalledWith(1, 1)
    expect(earn.volume).toHaveBeenLastCalledWith(.4, 1)
    player.event(gained, 1)
    player.event(stolen, 1)
    expect(earn.play).toHaveBeenCalledTimes(3)
    player.configure({ music: .2, effects: 0, muted: false })
    player.event(granted, 1)
    expect(earn.play).toHaveBeenCalledTimes(3)
    player.dispose()
  })
})
